"""Shared helpers for Kuraka vault scripts — ONE source of truth for project
identity and the central store layout, so every tool (init, archive, backup,
restore, discover) agrees on a project's slug and where its data lives.

No external dependencies. Importable because each script is invoked as
`python3 <vault>/<script>.py …`, which puts <vault> (this file's dir) on sys.path.

Central store layout (decided 2026-06-28 — single directory per project):

    <vault>/projects/
        INDEX.md                  rolling cross-project catalog (autogenerated)
        <slug>/
            registry.md           the project's registry note (path, stack, mode, branches)
            layer/                snapshot of the project's .claude/project/ specialization
            state/                snapshot of in-flight Kuraka artifacts (docs/process/**)
            cycles/<REQ>/         closed-cycle diagnostics (RETRO + telemetry + meta.yaml)
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path


def force_utf8_io() -> None:
    """Emit UTF-8 no matter the console code page. Windows' legacy console
    (cp1252/cp850) otherwise raises UnicodeEncodeError on our emoji/box-drawing
    output. Importing this module applies it, so every CLI tool is covered."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")  # Python 3.7+
        except (AttributeError, ValueError, OSError):
            pass


force_utf8_io()

STORE_DIRNAME = "projects"


def slugify(name: str) -> str:
    """Lowercase, hyphen-separated, alphanumeric slug."""
    s = re.sub(r"[^a-zA-Z0-9]+", "-", name).strip("-").lower()
    return s or "project"


def project_slug(project: Path, override: str | None = None) -> str:
    """Canonical slug for a project. Order of preference:
      1. explicit override (slugified),
      2. kuraka.config.yaml `project.name` (slugified),
      3. the project folder name (slugified).

    Reading `project.name` first is what keeps init/archive/backup/restore in
    agreement — keying off the folder name vs the config name was the source of
    the clinica `clinicaDental2026` vs `clinica-dental-2026` drift.
    """
    if override:
        return slugify(override)
    cfg = project / "kuraka.config.yaml"
    if cfg.exists():
        in_project = False
        for line in cfg.read_text(encoding="utf-8", errors="ignore").splitlines():
            if re.match(r"^project:\s*$", line):
                in_project = True
                continue
            if in_project:
                m = re.match(r"^\s+name:\s*(.+?)\s*$", line)
                if m:
                    return slugify(m.group(1).strip().strip("\"'"))
                if re.match(r"^\S", line):  # left the project: block
                    break
    return slugify(project.name)


def git_branch(project: Path) -> str:
    """Current git branch of the project, or a sentinel if unavailable."""
    try:
        out = subprocess.run(
            ["git", "-C", str(project), "rev-parse", "--abbrev-ref", "HEAD"],
            capture_output=True, text=True, timeout=5,
        )
        if out.returncode == 0:
            return out.stdout.strip() or "(detached)"
    except (OSError, subprocess.SubprocessError):
        pass
    return "(no-git)"


# --- central store paths (all derive from one place) ---

def store_root(vault: Path) -> Path:
    return vault / STORE_DIRNAME


def project_dir(vault: Path, slug: str) -> Path:
    return store_root(vault) / slug


def registry_note(vault: Path, slug: str) -> Path:
    return project_dir(vault, slug) / "registry.md"


def layer_dir(vault: Path, slug: str) -> Path:
    return project_dir(vault, slug) / "layer"


def state_dir(vault: Path, slug: str) -> Path:
    return project_dir(vault, slug) / "state"


def cycles_dir(vault: Path, slug: str) -> Path:
    return project_dir(vault, slug) / "cycles"


def overrides_dir(vault: Path, slug: str) -> Path:
    return project_dir(vault, slug) / "overrides"


def has_history(vault: Path, slug: str) -> bool:
    """True if the central store holds restorable data for this project."""
    p = project_dir(vault, slug)
    if not p.is_dir():
        return False
    return any((p / sub).is_dir() and any((p / sub).iterdir())
               for sub in ("layer", "state", "cycles", "overrides"))


# --- project-specific overrides (agent/skill/command tunings) -----------------
# Consumer projects often tune a framework agent to their needs (e.g. edit
# .claude/agents/backend-developer.md). Those dirs are gitignored AND overwritten
# by the vault rsync on every mount, so the tuning is otherwise lost. We detect
# files that diverge from the vault baseline, snapshot them centrally, and
# re-apply them after each mount (the project override wins).

OVERRIDE_CATEGORIES = ("agents", "skills", "commands")

MOUNT_MANIFEST_NAME = ".kuraka-mount-manifest.json"


def _file_hash(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def load_mount_manifest(project: Path) -> dict[str, str]:
    """Vault-baseline hashes recorded at mount time ('<cat>/<rel>' -> sha256).
    Empty dict when the project pre-dates the manifest (legacy mounts)."""
    p = project / ".claude" / MOUNT_MANIFEST_NAME
    if not p.is_file():
        return {}
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    files = data.get("files", {})
    if not isinstance(files, dict):
        return {}
    return {str(k): str(v) for k, v in files.items()}


def write_mount_manifest(project: Path, vault: Path,
                         categories: tuple[str, ...] = OVERRIDE_CATEGORIES) -> int:
    """Record the vault-baseline hash of every mountable file in `categories`,
    merging over any existing manifest (categories not mounted this time keep
    their old entries). detect_overrides uses this to tell 'the project never
    touched it' (vault staleness -> refresh on next mount) from 'the project
    edited it' (real override -> preserve). Returns entries written."""
    manifest = load_mount_manifest(project)
    count = 0
    for cat in categories:
        src = vault / cat
        if not src.is_dir():
            continue
        manifest = {k: v for k, v in manifest.items() if not k.startswith(f"{cat}/")}
        for p in sorted(src.rglob("*.md")):
            if p.name.endswith(".append.md"):
                continue
            key = (Path(cat) / p.relative_to(src)).as_posix()
            manifest[key] = _file_hash(p)
            count += 1
    out = project / ".claude" / MOUNT_MANIFEST_NAME
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"files": manifest}, indent=1, sort_keys=True) + "\n",
                   encoding="utf-8")
    return count


_WIKILINK_RE = re.compile(rb"\[\[([^\]|]+)\]\]")


def _normalize_legacy_format(data: bytes) -> bytes:
    """Collapse the legacy mount-time formatting drift: old mounts converted
    vault wikilinks ([[name]]) to runtime backticks (`name`) while copying, so
    a project file can differ from every committed vault version by formatting
    alone. Applying the same conversion to BOTH sides before hashing removes
    that confound without hiding real content edits."""
    return _WIKILINK_RE.sub(rb"`\1`", data)


def _matches_vault_history(vault: Path, rel: str, file_hash: str,
                           norm_hash: str | None = None) -> bool:
    """Legacy-fallback staleness test (projects mounted before the manifest
    existed): True if `file_hash` equals ANY committed vault version of `rel`,
    byte-for-byte or after legacy wikilink normalization on both sides (old
    mounts rewrote [[x]] -> `x` while copying, e.g. guai's review-migrations.md
    2026-07). A historical match proves the project never edited the file."""
    try:
        commits = subprocess.run(
            ["git", "log", "--format=%H", "--", rel],
            capture_output=True, text=True, cwd=vault, check=False,
        ).stdout.split()
    except OSError:
        return False
    for c in commits:
        r = subprocess.run(["git", "show", f"{c}:{rel}"],
                           capture_output=True, cwd=vault, check=False)
        if r.returncode != 0:
            continue
        if hashlib.sha256(r.stdout).hexdigest() == file_hash:
            return True
        if norm_hash is not None and hashlib.sha256(
                _normalize_legacy_format(r.stdout)).hexdigest() == norm_hash:
            return True
    return False


def detect_overrides(project: Path, vault: Path) -> list[Path]:
    """Relative paths (as `<cat>/<rel>`) under .claude/<cat>/ whose content differs
    from the vault baseline, or that don't exist in the vault at all (custom
    files). These are the project-specific tunings worth preserving.

    A file that differs from the CURRENT vault but still matches the baseline
    recorded in the mount manifest was never touched by the project — that is
    vault staleness, NOT a tuning, and it is skipped so the next mount can
    refresh it. (kuraka-control 2026-07: 27 stale files were snapshotted as
    "overrides" and would have pinned the project to a June framework forever.)
    Legacy projects without a manifest keep the old behavior (divergence =
    override) until their first manifest-writing mount.

    Excludes *.append.md (project-layer rule fragments — never framework files,
    already excluded by the mount rsync). Vault and project both store backticked
    cross-refs (no wikilink conversion in mount-kuraka.sh), so a byte comparison
    is exact — no false positives from formatting differences.
    """
    out: list[Path] = []
    manifest = load_mount_manifest(project)
    for cat in OVERRIDE_CATEGORIES:
        proj_cat = project / ".claude" / cat
        vault_cat = vault / cat
        if not proj_cat.is_dir():
            continue
        for p in sorted(proj_cat.rglob("*.md")):
            if p.name.endswith(".append.md"):
                continue
            rel = p.relative_to(proj_cat)
            base = vault_cat / rel
            proj_hash = _file_hash(p)
            if base.exists() and proj_hash == _file_hash(base):
                continue  # identical to the current vault — nothing to preserve
            key = (Path(cat) / rel).as_posix()
            if key in manifest and proj_hash == manifest[key]:
                continue  # untouched since mount — vault staleness, not a tuning
            if key not in manifest and base.exists():
                norm_hash = hashlib.sha256(
                    _normalize_legacy_format(p.read_bytes())).hexdigest()
                if _matches_vault_history(vault, key, proj_hash, norm_hash):
                    continue  # legacy mount matching a committed vault version
                    #           (raw or wikilink-normalized) — stale, not a tuning
            out.append(Path(cat) / rel)
    return out


def snapshot_overrides(project: Path, vault: Path, slug: str) -> int:
    """Copy divergent agent/skill/command files into the central overrides store,
    preserving <cat>/<rel>, and rewrite MANIFEST.md. If nothing diverges, clear the
    store subdir so a reverted tuning doesn't linger and get re-applied later.
    Returns the number of override files snapshotted."""
    dst_root = overrides_dir(vault, slug)
    rels = detect_overrides(project, vault)
    if dst_root.exists():
        shutil.rmtree(dst_root)          # start clean each snapshot
    if not rels:
        return 0
    lines = [
        "# Overrides — project-specific tunings snapshotted from .claude/",
        "",
        f"project: {slug}",
        f"snapshot: {date.today().isoformat()}",
        "",
        "Re-applied on top of the vault copy after every mount (project wins).",
        "",
        "| Archivo | Hash |",
        "|---|---|",
    ]
    for rel in rels:
        src = project / ".claude" / rel
        d = dst_root / rel
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, d)
        lines.append(f"| `{rel}` | `{_file_hash(src)[:12]}` |")
    (dst_root / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(rels)


def restore_overrides(vault: Path, slug: str, project: Path) -> int:
    """Re-apply snapshotted overrides on top of the freshly-mounted vault copy
    (project override wins). Overwrites unconditionally — that's the point. Only
    the known category subdirs are copied (MANIFEST.md stays central). Returns the
    number of files re-applied."""
    src_root = overrides_dir(vault, slug)
    if not src_root.is_dir():
        return 0
    copied = 0
    for cat in OVERRIDE_CATEGORIES:
        src_cat = src_root / cat
        if not src_cat.is_dir():
            continue
        for s in src_cat.rglob("*"):
            if s.is_dir():
                continue
            rel = s.relative_to(src_cat)
            d = project / ".claude" / cat / rel
            d.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(s, d)
            copied += 1
    return copied


# --- snapshot + cycle archiving (shared by kuraka-backup / kuraka-archive) ---

def snapshot_tree(src: Path, dst: Path) -> int:
    """Mirror src into dst (copy, overwrite). Returns number of files copied.
    Used to snapshot the project's .claude/project (layer) and docs/process (state)
    into the central store. No deletes on dst beyond the subtree it owns."""
    if not src.is_dir():
        return 0
    n = 0
    for s in src.rglob("*"):
        if s.is_dir():
            continue
        rel = s.relative_to(src)
        d = dst / rel
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(s, d)
        n += 1
    return n


def find_verdict(retro_text: str) -> str:
    for pat in (r"##\s*Confidence:\s*(.+)", r"Confidence:\s*(\w+)", r"Verdict:\s*(.+)"):
        m = re.search(pat, retro_text)
        if m:
            return m.group(1).strip()[:60]
    return ""


def _retro_dirs(project: Path, docs_root: str) -> list[Path]:
    docs = project / docs_root
    candidates = [
        docs / "agent-retrospectives",
        docs / "retros",
        project / "backend" / docs_root / "agent-retrospectives",
    ]
    return [d for d in candidates if d.is_dir()]


def archive_cycles(project: Path, vault: Path, slug: str, branch: str,
                   docs_root: str, force: bool) -> list[dict]:
    """Copy each cycle's RETRO (+ telemetry) into <vault>/projects/<slug>/cycles/<REQ>/.
    Returns one row dict per cycle (status archived|skip + verdict + telem flag)."""
    today = date.today().isoformat()
    dest_root = cycles_dir(vault, slug)
    telem_dirs = [project / docs_root / "agent-telemetry",
                  project / "backend" / docs_root / "agent-telemetry"]

    retros_by_name: dict[str, Path] = {}
    for d in _retro_dirs(project, docs_root):
        for p in sorted(d.glob("RETRO-*.md")):
            if p.name == "RETRO-LATEST.md":
                continue
            retros_by_name.setdefault(p.name, p)

    rows: list[dict] = []
    for name in sorted(retros_by_name):
        retro = retros_by_name[name]
        req = retro.stem[len("RETRO-"):] if retro.stem.startswith("RETRO-") else retro.stem
        dest = dest_root / req
        if dest.exists() and not force:
            rows.append({"req": req, "status": "skip"})
            continue
        dest.mkdir(parents=True, exist_ok=True)
        retro_text = retro.read_text(encoding="utf-8", errors="ignore")
        shutil.copy2(retro, dest / retro.name)
        telem_candidates = [d / f"{req}-telemetry.json" for d in telem_dirs]
        telem_candidates.append(retro.parent.parent / "agent-telemetry" / f"{req}-telemetry.json")
        telem = next((t for t in telem_candidates if t.exists()), None)
        if telem:
            shutil.copy2(telem, dest / telem.name)
        verdict = find_verdict(retro_text)
        (dest / "meta.yaml").write_text(
            f"project: {slug}\nreq: {req}\nbranch: {branch}\narchived_at: {today}\n"
            f"source_retro: {retro}\nhas_telemetry: {str(telem is not None).lower()}\n"
            f"verdict: \"{verdict}\"\n",
            encoding="utf-8",
        )
        rows.append({"req": req, "status": "archived", "verdict": verdict,
                     "telem": telem is not None, "branch": branch})
    return rows


def update_index(vault: Path, rows: list[dict], slug: str, force: bool) -> int:
    """Append archived cycles to <vault>/projects/INDEX.md (rolling catalog)."""
    index = store_root(vault) / "INDEX.md"
    today = date.today().isoformat()
    if not index.exists():
        index.parent.mkdir(parents=True, exist_ok=True)
        index.write_text(
            "# Projects — cross-project cycle index\n\n"
            "One row per archived Kuraka cycle, across all projects. Feeds cross-project\n"
            "pattern-detection. Append-only.\n\n"
            "| Archived | Project | Cycle (REQ) | Branch | Verdict | Telemetry |\n"
            "|---|---|---|---|---|---|\n",
            encoding="utf-8",
        )
    text = index.read_text(encoding="utf-8")
    new_lines: list[str] = []
    for r in rows:
        if r["status"] != "archived":
            continue
        key = f"| {slug} | {r['req']} "
        if (key in text or any(key in nl for nl in new_lines)) and not force:
            continue
        tel = "✓" if r.get("telem") else "—"
        br = r.get("branch", "—") or "—"
        new_lines.append(
            f"| {today} | {slug} | {r['req']} | {br} | {r.get('verdict','') or '—'} | {tel} |")
    if new_lines:
        index.write_text(text.rstrip() + "\n" + "\n".join(new_lines) + "\n", encoding="utf-8")
    return len(new_lines)
