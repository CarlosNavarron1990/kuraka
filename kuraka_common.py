MOUNT_MANIFEST_NAME = ".kuraka-mount-manifest.json"


# --- Claude-only frontmatter keys ---------------------------------------------
# The vault stores agent/skill frontmatter as the CLAUDE-NATIVE SUPERSET (the
# `model:` precedent, extended by AGENT-HARNESS.yaml: tools/maxTurns/etc.).
# Non-Claude renders (Antigravity, Cursor, Codex) SUBTRACT these keys at copy
# time so a platform never receives harness fields it doesn't understand.
# Claude renders stay byte-identical to the vault — that is what keeps
# detect_overrides() a safe byte comparison. Never inject frontmatter at mount
# time for the claude target.

CLAUDE_ONLY_FRONTMATTER_KEYS = {
    # subagent harness keys (AGENT-HARNESS.yaml)
    "tools", "disallowedtools", "permissionmode", "maxturns", "skills",
    "memory", "effort", "background", "isolation", "hooks", "mcpservers",
    "initialprompt",
    # skill frontmatter keys (Claude Code SKILL.md contract)
    "disable-model-invocation", "user-invocable", "context",
    "allowed-tools", "disallowed-tools",
}


def strip_claude_frontmatter(text: str) -> str:
    """Remove Claude-Code-only keys from a Markdown file's YAML frontmatter.

    Handles single-line values and indented/block continuations of a stripped
    key. The body and all other frontmatter lines pass through untouched; text
    without a frontmatter block is returned as-is."""
    if not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    if end == -1:
        return text
    kept: list[str] = []
    skipping = False
    for line in text[3:end].split("\n"):
        stripped = line.strip()
        indent = len(line) - len(line.lstrip(" "))
        if skipping:
            # continuation lines of a stripped key (indented, or list items)
            if stripped and (indent > 0 or stripped.startswith("-")):
                continue
            skipping = False
        if ":" in stripped and indent == 0:
            key = stripped.split(":", 1)[0].strip().lower()
            if key in CLAUDE_ONLY_FRONTMATTER_KEYS:
                skipping = True
                continue
        kept.append(line)
    return "---" + "\n".join(kept) + text[end:]


# --- platform rendering (single source of truth) ------------------------------
# What a mount actually WRITES for a given platform. kuraka-mount.py::copy_file
# delegates here, and write_mount_manifest() hashes the output of the very same
# function — that is what makes the mount manifest a valid baseline on non-Claude
# platforms. Before this existed the manifest stored the *vault* hash while the
# mounted file was a render, so every mounted file on Antigravity/Cursor/Codex
# read as a "project override" (petsuite 104, camisassis 153, codex 52), the
# whole suite got snapshotted and re-applied on each mount, and the project was
# frozen on an old framework version forever.

_DISCIPLINE_RE = re.compile(r"<!-- kuraka:discipline:([A-Za-z0-9_-]+) -->")

# platform alias -> platform directory name (the dir is `.<name>`)
_PLATFORM_ALIASES = {"antigravity": "agents", "agents": "agents",
                     "claude": "claude", "codex": "codex", "cursor": "cursor"}


def platform_key(platform: str) -> str:
    """Normalize a platform/target name to its directory name without the dot
    ('antigravity' -> 'agents', '.codex' -> 'codex')."""
    p = (platform or "claude").lstrip(".").strip().lower()
    return _PLATFORM_ALIASES.get(p, p)


def platform_dirname(platform: str) -> str:
    """'.claude', '.agents', '.codex', '.cursor'."""
    return f".{platform_key(platform)}"


def expand_discipline(text: str, vault: Path) -> str:
    """Expand `<!-- kuraka:discipline:<name> -->` markers with the full manual
    discipline prose from <vault>/discipline/<name>.md. Claude renders keep the
    slim hook-note + marker (the harness enforces the rule there); non-Claude
    renders get the complete manual discipline back, so no platform loses the
    rule when Claude's prompts slim down."""
    def _sub(m: "re.Match[str]") -> str:
        block = vault / "discipline" / f"{m.group(1)}.md"
        if block.is_file():
            return block.read_text(encoding="utf-8", errors="ignore").rstrip("\n")
        return m.group(0)

    return _DISCIPLINE_RE.sub(_sub, text)


def adapt_antigravity_paths(text: str) -> str:
    """.claude/<x>/ -> .agents/<x>/ path projection for the Antigravity mount."""
    for sub in ("skills", "rules", "agents", "project", "stack-profiles", "templates"):
        text = text.replace(f".claude/{sub}/", f".agents/{sub}/")
    return text


def adapt_codex_paths(text: str) -> str:
    """Translate Claude paths and command mentions to the Codex projection.

    Root Markdown skills become SKILL.md directories in Codex, so convert the
    common explicit `.md` references before applying the broader replacements."""
    text = re.sub(r"\.claude/skills/([A-Za-z0-9_-]+)\.md",
                  r".codex/skills/\1/SKILL.md", text)
    text = (text.replace(".claude/skills/", ".codex/skills/")
                .replace(".claude/rules/", ".codex/rules/")
                .replace(".claude/agents/", ".codex/agents/")
                .replace(".claude/project/", ".codex/project/")
                .replace(".claude/stack-profiles/", ".codex/stack-profiles/")
                .replace(".claude/templates/", ".codex/templates/")
                .replace(".claude/", ".codex/")
                .replace("Requires a Claude Code restart afterward.",
                         "Requires a new Codex session afterward."))
    text = text.replace(
        'kuraka-backup.py" <project-root>',
        'kuraka-backup.py" <project-root> --layer-root .codex/project --skip-overrides',
    )
    for name in ("checkmarx-remediation", "kuraka-wizard", "kuraka-backup",
                 "kuraka-update", "kuraka-ahorro", "kuraka", "amauta", "inti",
                 "arki"):
        text = text.replace(f"/prompts:{name}", f"${name}")
        text = re.sub(rf"(?<![A-Za-z0-9_.$/])/{re.escape(name)}(?![A-Za-z0-9_.-])",
                      f"${name}", text)
    return text


# --- Claude account plan (model routing per subscription) ---------------------
# MODEL-ROUTING.yaml `claude_plans:` maps each Claude subscription to a
# tier -> model column. The VAULT frontmatter is always the `max` column (=
# platforms.claude, applied by kuraka-apply-models.py), so a `max` mount stays
# the byte-identical copy the override subsystem relies on. Any other plan is a
# RENDER that rewrites only the agent `model:` line — done inside
# render_for_platform, the same function the mount manifest hashes, so a
# pro/team mount does not read as 24 project overrides. The active plan of a
# project is recorded in its mount manifest (`claude_plan`) and re-read by
# detect_overrides / every later --update, so it is chosen once per project.

CLAUDE_PLANS = ("max", "pro", "team")
DEFAULT_CLAUDE_PLAN = "max"
_CLAUDE_PLAN: "str | None" = None
_ROUTING_CACHE: dict = {}


def normalize_claude_plan(plan: "str | None") -> "str | None":
    """'max'/'pro'/'team' (aliases: promax, max5, max20, teams, 20); None if unknown."""
    if not plan:
        return None
    v = str(plan).strip().lower().replace(" ", "").replace("-", "").replace("_", "")
    aliases = {"max": "max", "promax": "max", "max5": "max", "max20": "max",
               "pro": "pro", "20": "pro", "20usd": "pro",
               "team": "team", "teams": "team"}
    return aliases.get(v)


def set_claude_plan(plan: "str | None") -> str:
    """Set the plan claude renders use in this process; returns the effective plan."""
    global _CLAUDE_PLAN
    _CLAUDE_PLAN = normalize_claude_plan(plan) or DEFAULT_CLAUDE_PLAN
    return _CLAUDE_PLAN


def active_claude_plan() -> str:
    return _CLAUDE_PLAN or DEFAULT_CLAUDE_PLAN


def load_model_routing(vault: Path) -> dict:
    """Parse MODEL-ROUTING.yaml (fixed shape, no PyYAML): tiers, platforms,
    claude_plans (one nested level each) and agents."""
    path = vault / "MODEL-ROUTING.yaml"
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return {"tiers": {}, "platforms": {}, "claude_plans": {}, "agents": {}}
    key = (str(path), mtime)
    if key in _ROUTING_CACHE:
        return _ROUTING_CACHE[key]
    out: dict = {"tiers": {}, "platforms": {}, "claude_plans": {}, "agents": {}}
    section, sub = None, None
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip())
        line = raw.strip().split(" #", 1)[0].strip()
        if ":" not in line:
            continue
        k, _, v = line.partition(":")
        k, v = k.strip(), v.strip().strip('"').strip("'")
        if indent == 0:
            section = k if k in out else None
            sub = None
            continue
        if section in ("tiers", "agents"):
            out[section][k] = v
        elif section in ("platforms", "claude_plans"):
            if indent == 2:
                sub = k
                out[section][sub] = {}
            elif indent >= 4 and sub is not None:
                out[section][sub][k] = v
    _ROUTING_CACHE.clear()
    _ROUTING_CACHE[key] = out
    return out


def claude_plan_models(vault: Path, plan: "str | None" = None) -> dict:
    """tier -> Claude model for `plan` (falls back to platforms.claude)."""
    r = load_model_routing(vault)
    plan = normalize_claude_plan(plan) or active_claude_plan()
    return dict(r["claude_plans"].get(plan) or r["platforms"].get("claude") or {})


def claude_plan_is_identity(vault: Path, plan: "str | None" = None) -> bool:
    """True when `plan` renders agents exactly as the vault stores them."""
    r = load_model_routing(vault)
    base = r["platforms"].get("claude") or {}
    return claude_plan_models(vault, plan) == base


_FM_MODEL_RE = re.compile(r"^(model:[ \t]*)(\S.*?)[ \t]*$", re.M)


def apply_claude_plan(text: str, vault: Path, plan: "str | None" = None) -> str:
    """Rewrite an AGENT's frontmatter `model:` to its tier's model for `plan`.
    Non-agent files (skills, commands, contexts) and agents without a tier
    are returned untouched."""
    if claude_plan_is_identity(vault, plan) or not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    if end == -1:
        return text
    head = text[:end]
    m = re.search(r"^name:[ \t]*(\S+)", head, re.M)
    if not m:
        return text
    r = load_model_routing(vault)
    tier = r["agents"].get(m.group(1).strip().strip('"').strip("'"))
    model = claude_plan_models(vault, plan).get(tier or "")
    if not tier or not model:
        return text
    new_head, n = _FM_MODEL_RE.subn(lambda mm: mm.group(1) + model, head, count=1)
    return new_head + text[end:] if n else text


def manifest_claude_plan(project: Path) -> "str | None":
    """Plan recorded by the last claude mount of `project` (None if never)."""
    p = project / ".claude" / MOUNT_MANIFEST_NAME
    try:
        return normalize_claude_plan(json.loads(p.read_text(encoding="utf-8")).get("claude_plan"))
    except (OSError, json.JSONDecodeError, AttributeError):
        return None


def render_for_platform(text: str, platform: str, vault: Path) -> str:
    """The exact content a mount of `platform` writes for a vault .md file.

    Claude is the identity render (byte-identical copy of the vault superset);
    every other platform SUBTRACTS the Claude-only frontmatter, re-expands the
    manual discipline prose, and applies its path projection."""
    plat = platform_key(platform)
    if plat == "claude":
        return apply_claude_plan(text, vault)  # identity on the `max` plan
    text = strip_claude_frontmatter(text)
    text = expand_discipline(text, vault)
    if plat == "agents":
        return adapt_antigravity_paths(text)
    if plat == "codex":
        return adapt_codex_paths(text)
    return text  # cursor: no path projection at copy time


def split_frontmatter(text: str) -> "tuple[dict[str, str], str]":
    """(frontmatter mapping, body) for a Markdown file. Flat single-line keys
    only — enough for the name/description a Codex skill header needs."""
    fm: dict[str, str] = {}
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            for raw in text[3:end].splitlines():
                if ":" not in raw:
                    continue
                k, _, v = raw.partition(":")
                fm[k.strip()] = v.strip().strip('"').strip("'")
            return fm, text[end + 4:].lstrip("\n")
    return fm, text


